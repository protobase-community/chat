-- Editing, deleting and reacting to messages. A message keeps when its author last changed it, which the chat shows as
-- "(edited)"; null for one never changed. A reaction is one person's emoji under a message, one per person, message and
-- emoji, and goes with its message when that is deleted.

alter table public.messages add column edited_at timestamptz;

create function public.message_edited() returns trigger language plpgsql as $$
begin
  if new.body is distinct from old.body or new.mentions is distinct from old.mentions then
    new.edited_at := now();
  end if;
  return new;
end
$$;

create trigger messages_edited before update on public.messages
  for each row execute function public.message_edited();

-- The key of the composite foreign key below, so a reaction's workspace is always its message's.
alter table public.messages add constraint messages_id_organization unique (id, organization_id);

create table public.reactions (
  id integer generated by default as identity primary key,
  organization_id text not null,
  message_id integer not null,
  user_id text not null,
  emoji text not null check (emoji in ('thumbs_up', 'heart', 'laugh', 'surprised', 'sad', 'party')),
  created_at timestamptz not null default now(),
  foreign key (message_id, organization_id) references public.messages (id, organization_id) on delete cascade,
  -- One reaction per person, message and emoji; the message_id first also serves reading a page's reactions.
  unique (message_id, user_id, emoji)
);
