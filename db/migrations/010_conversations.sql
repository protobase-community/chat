-- Conversations only their members see: private channels and direct messages. A conversation keeps its members as
-- member_ids, a JSON array of user ids, which the access rules' row filters read through a GIN index. Its creator is
-- always one of them: a trigger adds the author the API stamps, and a check keeps them in.

-- A channel is public or private. The channels there are public, as is one an older version of the app creates.
alter table public.channels add column kind text not null default 'public' check (kind in ('public', 'private'));
alter table public.channels add column member_ids jsonb;
alter table public.channels add constraint channels_members check (
  (kind = 'public' and member_ids is null)
  or (kind = 'private' and jsonb_typeof(member_ids) = 'array' and member_ids ? author_id)
);

-- Only public channels' names are unique in a workspace, so starting a channel tells nobody a private one's name.
create unique index channels_public_name on public.channels (organization_id, name) where kind = 'public';
alter table public.channels drop constraint channels_organization_id_name_key;

create index channels_kind on public.channels (organization_id, kind);
create index channels_member_ids on public.channels using gin (member_ids);

-- Adds the author to a new conversation's members, so a creator who did not pick themselves is one.
create function public.add_author_to_members() returns trigger language plpgsql as $$
begin
  if new.member_ids is null then
    new.member_ids := '[]'::jsonb;
  end if;
  if jsonb_typeof(new.member_ids) = 'array' and not new.member_ids ? new.author_id then
    new.member_ids := new.member_ids || to_jsonb(new.author_id);
  end if;
  return new;
end
$$;

create trigger channels_author_member before insert on public.channels
  for each row when (new.kind = 'private') execute function public.add_author_to_members();

-- The members of a direct message as one text, sorted and without repeats, so one set of people has one conversation.
create function public.member_key(member_ids jsonb) returns text language sql immutable strict as $$
  select string_agg(id, ',' order by id) from (select distinct id collate "C" as id from jsonb_array_elements_text(member_ids) as each (id)) as ids
$$;

create table public.direct_messages (
  id integer generated by default as identity primary key,
  organization_id text not null,
  -- Its starter and at least one other person.
  member_ids jsonb not null check (jsonb_typeof(member_ids) = 'array' and member_ids ? author_id and public.member_key(member_ids) like '%,%'),
  author_id text not null,
  created_at timestamptz not null default now(),
  member_key text not null generated always as (public.member_key(member_ids)) stored,
  unique (organization_id, member_key),
  -- The key of the composite foreign key below, so a message's workspace is always its conversation's.
  unique (id, organization_id)
);

create trigger direct_messages_author_member before insert on public.direct_messages
  for each row execute function public.add_author_to_members();

create index direct_messages_member_ids on public.direct_messages using gin (member_ids);
create index direct_messages_created_at on public.direct_messages (created_at);

-- A message is in a channel or in a direct message, never both.
alter table public.messages alter column channel_id drop not null;
alter table public.messages add column direct_message_id integer;
alter table public.messages add foreign key (direct_message_id, organization_id) references public.direct_messages (id, organization_id);
alter table public.messages add constraint messages_one_conversation check ((channel_id is null) <> (direct_message_id is null));

create index messages_direct_message on public.messages (direct_message_id, id);
