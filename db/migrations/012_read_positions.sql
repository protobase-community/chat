-- How far each person has read each conversation: the newest message id they read to, which the unread marks and the
-- "New messages" line count from. A person reads and moves only their own; it only moves forward, so an older tab
-- writing late never marks read messages unread again.

create table public.read_positions (
  id integer generated by default as identity primary key,
  organization_id text not null,
  user_id text not null,
  channel_id integer,
  direct_message_id integer,
  last_read_id integer not null,
  foreign key (channel_id, organization_id) references public.channels (id, organization_id),
  foreign key (direct_message_id, organization_id) references public.direct_messages (id, organization_id),
  check ((channel_id is null) <> (direct_message_id is null)),
  -- One position per person and conversation; the user_id first also serves the list of one's own positions.
  unique (user_id, channel_id),
  unique (user_id, direct_message_id)
);

create index read_positions_channel on public.read_positions (channel_id);
create index read_positions_direct_message on public.read_positions (direct_message_id);

create function public.read_position_forward() returns trigger language plpgsql as $$
begin
  new.last_read_id := greatest(old.last_read_id, new.last_read_id);
  return new;
end
$$;

create trigger read_positions_forward before update on public.read_positions
  for each row execute function public.read_position_forward();

-- The unread counts filter a person's conversations' messages by who wrote them and whom they mention.
create index messages_author on public.messages (author_id);
create index messages_mentions on public.messages using gin (mentions);
