-- A workspace's channels and their messages. organization_id is the workspace, a Better Auth organization's id, which
-- the API sets from the session; author_id is the signed-in person's user id, which the API sets on every create.

create table public.channels (
  id integer generated by default as identity primary key,
  organization_id text not null,
  name text not null,
  topic text,
  author_id text not null,
  created_at timestamptz not null default now(),
  unique (organization_id, name),
  -- The key of the composite foreign key below, so a message's workspace is always its channel's.
  unique (id, organization_id)
);

create table public.messages (
  id integer generated by default as identity primary key,
  organization_id text not null,
  channel_id integer not null,
  author_id text not null,
  body text not null,
  -- The user ids of the people the message mentions, as a JSON array; [] for none.
  mentions jsonb not null check (jsonb_typeof(mentions) = 'array'),
  sent_at timestamptz not null default now(),
  foreign key (channel_id, organization_id) references public.channels (id, organization_id)
);

-- A channel's messages, newest first, as the chat reads them a page at a time: ids follow the order they were sent.
create index messages_channel on public.messages (channel_id, id);

-- The sidebar's channels, by name.
create index channels_name on public.channels (name);
