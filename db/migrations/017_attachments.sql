-- Files shared in messages. An attachment is one file of a message, added by the message's author: a composite foreign
-- key keeps its workspace and author the message's. A message holds text, files or both, so its body is null when it
-- has only files; a check at commit keeps every message holding one or the other. Deleting a message takes its
-- attachments first, through the API, so their files are scheduled for deletion too: the foreign key refuses otherwise.

alter table public.messages alter column body drop not null;

-- The key of the composite foreign key below.
alter table public.messages add constraint messages_id_organization_author unique (id, organization_id, author_id);

create table public.attachments (
  id integer generated by default as identity primary key,
  organization_id text not null,
  message_id integer not null,
  author_id text not null,
  -- The stored file's URI, as Protobase's file fields keep it.
  file text not null,
  -- An image's size in pixels, read from the upload; null for any other file.
  width integer,
  height integer,
  created_at timestamptz not null default now(),
  foreign key (message_id, organization_id, author_id) references public.messages (id, organization_id, author_id)
);

-- A page's attachments, read by their messages' ids.
create index attachments_message on public.attachments (message_id, id);

-- Refuses a message left with neither text nor files, checked at commit so a message and its files are written together.
create function public.message_has_content() returns trigger language plpgsql as $$
declare
  target integer;
begin
  if tg_table_name = 'messages' then
    target := new.id;
  else
    target := old.message_id;
  end if;
  if exists (
    select from public.messages message
    where message.id = target and message.body is null
      and not exists (select from public.attachments attachment where attachment.message_id = message.id)
  ) then
    raise exception 'A message holds text, files or both' using errcode = 'check_violation';
  end if;
  return null;
end
$$;

create constraint trigger messages_content after insert or update of body on public.messages
  deferrable initially deferred for each row execute function public.message_has_content();

create constraint trigger attachments_content after delete on public.attachments
  deferrable initially deferred for each row execute function public.message_has_content();
